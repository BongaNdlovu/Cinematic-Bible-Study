/**
 * Builds js/study/glossary-enrichment.js from the hand-written overrides in
 * js/study/glossary-enrichment-overrides.json.
 *
 * Only hand-written entries ship. Every other glossary entry keeps its base
 * text from js/study/sheet-glossary.js and has no "Proof & sources" section.
 * Nothing is generated or padded here.
 *
 * Run: node tools/verify/build_glossary_enrichment.mjs
 */
import fs from 'fs';
import path from 'path';
import vm from 'vm';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

// Newton-length targets. They are reported below; entries are never padded to meet them.
const MIN_SIMPLE = 145;
const MIN_HISTORY = 520;
const MIN_PROOF = 4;

function loadGlossary() {
  const gCtx = { window: {} };
  vm.createContext(gCtx);
  let glossSrc = fs.readFileSync(path.join(root, 'js/study/sheet-glossary.js'), 'utf8');
  glossSrc = glossSrc.replace(/\(function applyGlossaryEnrichment\(\)[\s\S]*?\}\)\(\);\s*/, '');
  vm.runInContext(glossSrc, gCtx);
  return gCtx.window.SHEET_GLOSSARY || [];
}

function pickField(overrideVal, baseVal) {
  if (typeof overrideVal === 'string' && overrideVal.trim().length > 0) return overrideVal.trim();
  return baseVal;
}

const glossary = loadGlossary();
const knownIds = new Set(glossary.map((e) => e.id));
const overridesPath = path.join(root, 'js/study/glossary-enrichment-overrides.json');
const overrides = JSON.parse(fs.readFileSync(overridesPath, 'utf8'));

const unknown = Object.keys(overrides).filter((id) => !knownIds.has(id));
if (unknown.length) {
  console.error(`Overrides name glossary ids that do not exist: ${unknown.join(', ')}`);
  process.exit(1);
}

const enrichment = {};
for (const e of glossary) {
  const o = overrides[e.id];
  if (!o) continue;
  // Hand-written entries ship exactly as written: no padding, no appended base text.
  enrichment[e.id] = {
    simple: pickField(o.simple, e.simple),
    history: pickField(o.history, e.history),
    proof: Array.isArray(o.proof) ? o.proof : [],
  };
}

const outPath = path.join(root, 'js/study/glossary-enrichment.js');
const body =
  '/* Generated by tools/verify/build_glossary_enrichment.mjs — edit glossary-enrichment-overrides.json then rebuild. */\n' +
  '(function () {\n' +
  '  window.GLOSSARY_ENRICHMENT = ' +
  JSON.stringify(enrichment, null, 2) +
  ';\n})();\n';
fs.writeFileSync(outPath, body, 'utf8');

const count = Object.keys(enrichment).length;
console.log(`Wrote ${count} hand-written entries to ${outPath}`);
console.log(`${glossary.length - count} entries keep base text and no Proof & sources section.`);

const short = { simple: 0, history: 0, proof: 0 };
for (const m of Object.values(enrichment)) {
  if (m.simple.length < MIN_SIMPLE) short.simple += 1;
  if (m.history.length < MIN_HISTORY) short.history += 1;
  if (m.proof.length < MIN_PROOF) short.proof += 1;
}
console.log(
  `Below Newton-length floors (simple>=${MIN_SIMPLE}, history>=${MIN_HISTORY}, proof>=${MIN_PROOF}): ` +
    `simple ${short.simple}, history ${short.history}, proof ${short.proof} of ${count} hand-written entries.`,
);
